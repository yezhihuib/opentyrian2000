"""Deterministic candidate registration only; no painted or filled pixels.

Run beside source file. Source artwork is generated by built-in image_gen.
Never edits the game worktree or original bank. Pair halves are identical.
"""
from pathlib import Path
from PIL import Image, ImageChops
import hashlib, json

root = Path(__file__).resolve().parent
source = root / 'single-missile-generated-v1.png'
mask_path = root.parent / 'next-art-audit-dualmissile169' / 'original-single-missile-mask12x28.png'
raw = Image.open(source).convert('RGBA')
crop = (166, 179, 661, 1723)
size = (80, 176)
offset = (8, 40)
art = raw.crop(crop).resize(size, Image.Resampling.LANCZOS)
single = Image.new('RGBA', (96, 224))
single.alpha_composite(art, offset)
mask = Image.open(mask_path).convert('L').resize(single.size, Image.Resampling.NEAREST)
alpha = single.getchannel('A')
outside = [v for v, m in zip(alpha.get_flattened_data(), mask.get_flattened_data()) if not m]
inside = [v for v, m in zip(alpha.get_flattened_data(), mask.get_flattened_data()) if m]
single.putalpha(ImageChops.multiply(alpha, mask))
single.save(root / 'single-missile-inward-v1.png')
pair = Image.new('RGBA', (192, 224))
pair.alpha_composite(single)
pair.alpha_composite(single, (96, 0))
pair.save(root / 'dual-missile-inward-v1.png')
report = {
    'status': 'ART CANDIDATE ONLY; not runtime-qualified',
    'operation': 'whole-object affine crop/resize/translate plus native-mask clip; no row warping or painting',
    'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
    'original_mask_sha256': hashlib.sha256(mask_path.read_bytes()).hexdigest(),
    'crop': crop, 'resized_content': size, 'offset': offset,
    'outside_alpha_mass_subpixels': sum(outside) / 255,
    'outside_alpha_ge128_count': sum(v >= 128 for v in outside),
    'outside_alpha_max': max(outside),
    'inside_alpha_mass_subpixels': sum(inside) / 255,
    'native_mask_subpixels': len(inside),
    'pair_halves_byte_identical': pair.crop((0, 0, 96, 224)).tobytes() == pair.crop((96, 0, 192, 224)).tobytes(),
    'outside_native_mask_after_registration': 0,
}
(root / 'inward-fit-v1.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
