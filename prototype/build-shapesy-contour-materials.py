#!/usr/bin/env python3
"""Rebuild immutable contour materials from the existing qualified master.

This does not paint or modify any source image or existing HDA. The same crop,
registration, lighting, and UV grids used by the original material recipe are
exposed to the ordered contour compositor, including newly covered edge pixels.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import numpy as np
from PIL import Image


def legacy(root):
    path = root / 'prototype/build-shapesy-platform-art.py'
    spec = importlib.util.spec_from_file_location('shapesy_material_recipe', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def input_paths(root):
    return legacy(root).input_paths(root) + (
        root / 'prototype/build-shapesy-platform-art.py',
        root / 'prototype/build-shapesy-contour-materials.py',
    )


def generate(root):
    recipe_builder = legacy(root)
    directory = root / 'authoring-inputs/shapesy-platform-current'
    recipe = json.loads((directory / 'recipe.json').read_text())
    assert tuple(row['id'] for row in recipe['tiles']) == tuple(recipe_builder.IDS)
    assert hashlib.sha256((directory / recipe['master']).read_bytes()).hexdigest() == recipe['master_sha256']
    master = Image.open(directory / recipe['master']).convert('RGBA')
    components = {}
    for name, component in recipe['components'].items():
        pixels = np.array(master.crop(component['crop']).resize(tuple(component['size']), Image.Resampling.LANCZOS))[:, :, :3]
        if 'periodic_registration' in component:
            pixels = recipe_builder.register_period(pixels, 0, component['periodic_registration'])
            pixels = recipe_builder.register_period(pixels, 1, component['periodic_registration'])
        if 'periodic_registration_x' in component:
            pixels = recipe_builder.register_period(pixels, 1, component['periodic_registration_x'])
        components[name] = pixels
    lines = ['/* Generated by build-shapesy-contour-materials.py. Do not hand-edit.',
             ' * Exact existing master components and source-semantic geometry;',
             ' * no new painting, native water RGB, or gameplay data. */']

    def array(name, pixels):
        raw = pixels.astype(np.uint8).tobytes()
        lines.append('static const Uint8 ' + name + '[] = {')
        for offset in range(0, len(raw), 32):
            lines.append(' ' + ', '.join(str(value) for value in raw[offset:offset + 32]) + ',')
        lines.append('};')

    array('shapesy_contour_deck', components['deck'])
    array('shapesy_contour_right', np.rint(components['side'] * recipe['lighting']['right_wall']))
    array('shapesy_contour_shadow', np.rint(components['side'] * recipe['lighting']['original_shadow']))
    array('shapesy_contour_bevel', np.rint(components['bevel'] * recipe['lighting']['beveled_rim']))
    masks = []
    for row in recipe['tiles']:
        path = directory / row['semantic_mask']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == row['semantic_sha256']
        masks.append(np.array(Image.open(path)))
    array('shapesy_contour_semantic', np.stack(masks))
    lines.append('static const int shapesy_contour_wall_offset[28] = {' + ', '.join(str(row['wall_v_offset']) for row in recipe['tiles']) + '};')
    return ('\n'.join(lines) + '\n').encode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    output = args.out or args.root / 'src/current_shapesy_contour_materials.h'
    output.write_bytes(generate(args.root))
    print(output)


if __name__ == '__main__':
    main()
