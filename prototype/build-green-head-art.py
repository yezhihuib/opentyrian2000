"""Reproduce the four formal green head PNGs from their selected generated atlas.

No original game data is required or included. A single shared extraction transform
is used for every frame; the engine applies no compensating per-frame offset.
"""
from pathlib import Path
from PIL import Image
import argparse, hashlib, json
repo = Path(__file__).resolve().parent.parent
art = repo/'assets/hd/artwork/green-head-energy-v4'
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--output', type=Path, required=True)
a = p.parse_args()
if a.output.exists(): p.error('Choose a new output directory; existing files are never overwritten')
m = json.loads((art/'identity.json').read_text())
sha = lambda data: hashlib.sha256(data).hexdigest()
atlas_file = art/m['selected_atlas']
assert sha(atlas_file.read_bytes()) == m['selected_atlas_sha256']
atlas = Image.open(atlas_file).convert('RGBA')
a.output.mkdir(parents=True)
crop = m['shared_crop']
for i, sid in enumerate(m['frame_ids']):
 x = crop['x0']+(i%2)*crop['pitch_x']; y = crop['y0']+(i//2)*crop['pitch_y']
 frame = atlas.crop((x,y,x+crop['width'],y+crop['height'])).resize((96,112),Image.Resampling.LANCZOS)
 entry = m['frames'][str(sid)]
 formal = Image.open(repo/entry['source_png'])
 assert frame.mode == formal.mode == 'RGBA' and frame.size == formal.size == (96,112)
 assert frame.tobytes() == formal.tobytes(), (sid,'decoded pixels differ')
 output = a.output/Path(entry['source_png']).name
 frame.save(output)
 assert sha(output.read_bytes()) == entry['source_png_sha256'], (sid,'PNG encoding differs; check Pillow version')
print('PASS: all four green head PNGs regenerated byte-for-byte with the shared transform')
