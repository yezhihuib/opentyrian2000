"""Regenerate orange static59 energy art from the selected generated source."""
from pathlib import Path
from PIL import Image
import argparse,json,hashlib
repo=Path(__file__).resolve().parents[1];art=repo/'assets/hd/artwork/orange-energy59-v3'
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
if a.output.exists():p.error('Choose a new output directory')
m=json.loads((art/'identity.json').read_text());src=art/m['transform']['source'];sha=lambda b:hashlib.sha256(b).hexdigest()
assert sha(src.read_bytes())==m['source_sha256']
im=Image.open(src).crop(tuple(m['transform']['crop'])).resize(tuple(m['transform']['resize']),Image.Resampling.LANCZOS)
a.output.mkdir(parents=True);dest=a.output/Path(m['formal_runtime']['source_png']).name;im.save(dest)
assert sha(dest.read_bytes())==m['png_sha256']
assert dest.read_bytes()==(repo/m['formal_runtime']['source_png']).read_bytes()
print('PASS: orange59 PNG regenerated byte-for-byte; same12x14/anchor(-1,0)')
