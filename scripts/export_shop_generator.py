#!/usr/bin/env python3
"""Export the accepted generator v9 as an independent fixed PSP1 resource.

Original binary support validates the contour only; it never clips RGBA art.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct
from PIL import Image, ImageChops, ImageFilter
from export_shop_equipment import fnv, support

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/shop-generator-v1'
SOURCE_SHA = 'da19e9514a9f5874f2366f8e1123588994aaea454d2b8c1b31e359fd30755206'
PNG_SHA = '055fac0da3b71700e9616af36d78bd0664376a45bb81175f41057cea271218cc'
SP = dict(bank=6, index=16, size=(31,35), anchor=(62,84), rle_bytes=959,
          rle=0xef17480633ee6a68, index_hash=0xf4c1e126306f62fa, mask=0x80b82cd8620511c6)


def export(data):
    source = ASSETS/'source-imagegen.png'
    assert hashlib.sha256(source.read_bytes()).hexdigest() == SOURCE_SHA
    original = Image.open(source).convert('RGBA')
    assert original.size == (1180,1333)
    # The reviewed whole-subject crop is fixed. No original-mask fitting occurs.
    rgba = original.crop((0,0,1180,1323)).resize((124,140),Image.Resampling.LANCZOS)
    raw = bytearray(rgba.tobytes())
    removed = sum(0 < raw[p+3] < 8 for p in range(0,len(raw),4))
    for p in range(0,len(raw),4):
        if raw[p+3] < 8:
            raw[p:p+4] = bytes(4)
    rgba = Image.frombytes('RGBA',(124,140),bytes(raw))
    allowed = support(data,SP).filter(ImageFilter.MaxFilter(3)).resize((124,140),Image.Resampling.NEAREST)
    excess = ImageChops.subtract(rgba.getchannel('A').point(lambda a:255 if a else 0),allowed)
    outside = sum(bool(v) for v in excess.tobytes())
    assert outside == 0, 'Artwork exceeds the existing one-cell runtime guard'
    payload_hash = fnv(raw)
    fields = [1,6,16,31,35,4,124,140,62,84,len(raw),4,1,1,0]
    header = b'PSP1'+struct.pack('<15I',*fields)+struct.pack('<8Q',
        0x45a77a2246c174b9,0x1c6687307999bd82,SP['rle'],SP['index_hash'],SP['mask'],payload_hash,0,0)
    assert len(header) == 128 and len(raw) == 69440
    dest = ASSETS/'shop-generator-weapon16-v1.hda'
    dest.write_bytes(header+raw)
    rgba.save(dest.with_suffix('.png'))
    assert hashlib.sha256(dest.with_suffix('.png').read_bytes()).hexdigest() == PNG_SHA
    manifest = dict(format='PSP1',header_bytes=128,part='generator',
        source=dict(file='source-imagegen.png',sha256=SOURCE_SHA,size=[1180,1333],crop_xyxy=[0,0,1180,1323],
                    provenance='OpenAI imagegen; reviewed generator v9'),
        normalization='Reviewed fixed whole-subject crop -> direct 124x140 RGBA Lanczos; alpha<8 and RGB zeroed; no original-mask clipping',
        alpha_below_8_zeroed_samples=removed,outside_runtime_one_logical_cell_samples=outside,
        bank=6,index=16,logical_size=[31,35],density=4,anchor=[62,84],
        rgba='straight RGBA8; transparent RGB zero; continuous authored alpha',
        payload_bytes=len(raw),payload_fnv1a=f'0x{payload_hash:016x}',
        file_sha256=hashlib.sha256(header+raw).hexdigest(),png_sha256=PNG_SHA,pillow=Image.__version__,
        original_rle_fnv1a=f'0x{SP["rle"]:016x}',original_index_fnv1a=f'0x{SP["index_hash"]:016x}',original_mask_fnv1a=f'0x{SP["mask"]:016x}',
        runtime='Independent optional SFN1 sibling; known Talon assembly after original hull, before front; fixed generator anchor')
    dest.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (ROOT/'src/shop_generator_sprite_pins.h').write_text(
        '/* SPDX-License-Identifier: GPL-2.0-or-later */\n'
        '/* Generated by scripts/export_shop_generator.py from the reviewed generator v9. */\n'
        f'#define PF_GENERATOR_HASH UINT64_C(0x{payload_hash:016x})\n')
    print(json.dumps(manifest,indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--data',type=Path,required=True)
    args = parser.parse_args()
    export(args.data)
