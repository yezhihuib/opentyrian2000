#!/usr/bin/env python3
"""Reproducible, optional seven-label whole-run typography for shop root only.

No original art is input or redistributed. Natural FreeType advances are kept;
the original sprite-font commands remain the runtime's indexed proof/replay.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import struct
from PIL import Image, ImageDraw, ImageFont, features
import PIL

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/shop-menu-font-v1'
FONT_SHA = 'a4c5bc453ca281d90ea079e596da7ae0dfeb5777497c29ec254e76d97ff6f890'
RUNS = [('Game Menu', None, 20, 36), ('Data', 332, 76, 26),
        ('Ship Specs', 332, 108, 26), ('Upgrade Ship', 332, 140, 26),
        ('Options', 332, 172, 26), ('Start Level', 332, 204, 26),
        ('Quit Game', 332, 268, 26)]


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return value


def export(destination, pins):
    assert PIL.__version__ == '12.3.0'
    assert features.version('freetype2') == '2.14.3'
    assert features.version('raqm') == '0.10.5'
    font_path = ASSETS / 'DejaVuSans-Bold.ttf'
    assert hashlib.sha256(font_path.read_bytes()).hexdigest() == FONT_SHA
    destination.mkdir(parents=True, exist_ok=True)
    records, declarations, payload_bytes = [], [], 0
    # Reviewed preview is 640x400 at 8x. Export that exact shaping at 1280x800,
    # reducing uniformly by four; no independent glyph fit or runtime font.
    scale = 8
    for number, (text, x, top, size) in enumerate(RUNS):
        font = ImageFont.truetype(str(font_path), size * scale)
        cap = -font.getbbox('H', anchor='ls')[1] / scale
        baseline = top + cap
        advance = font.getlength(text) / scale
        if x is None:
            x = 468 - advance / 2
        left, upper, right, lower = font.getbbox(text, anchor='ls')
        sx, sy = round(x * scale), round(baseline * scale)
        ox, oy = math.floor((sx + left) / 4) - 1, math.floor((sy + upper) / 4) - 1
        w, h = math.ceil((sx + right) / 4) + 1 - ox, math.ceil((sy + lower) / 4) + 1 - oy
        mask = Image.new('L', (w * 4, h * 4))
        ImageDraw.Draw(mask).text((sx - ox * 4, sy - oy * 4), text,
                                  font=font, fill=255, anchor='ls')
        alpha = mask.resize((w, h), Image.Resampling.BOX).tobytes()
        roles = bytearray(w * h)
        for yy in range(h):
            y = (oy + yy + .5) / 2
            role = 15 if y < top + 1.2 else 14 if y < top + 2.55 else 12 if baseline - 1.05 <= y < baseline else 13
            for xx in range(w):
                if alpha[yy * w + xx]:
                    roles[yy * w + xx] = role
        payload = alpha + roles
        payload_bytes += len(payload)
        name = f'shop-menu-run{number}-v1.hda'
        fields = [1, number, 4, ox, oy, w, h, w * h, w * h,
                  12, 15, 8, 8, 0 if number == 0 else number + 1, len(text)]
        header = b'SMR1' + struct.pack('<15I', *fields)
        header += struct.pack('<8Q', fnv(text.encode()), 0x845b16939661b466,
            0x45a77a2246c174b9, 0x1c6687307999bd82, fnv(payload), 0, 0, 0)
        assert len(header) == 128 and ox >= 0 and oy >= 0 and ox + w + 8 <= 1280 and oy + h + 8 <= 800
        (destination / name).write_bytes(header + payload)
        records.append(dict(id=number, text=text, file=name, output_xywh=[ox, oy, w, h],
            anchor_native_640=[x, top], baseline_native_640=baseline,
            font_size_native_640=size, natural_advance_native_640=advance,
            payload_bytes=len(payload), payload_fnv1a=f'0x{fnv(payload):016x}',
            file_sha256=hashlib.sha256(header + payload).hexdigest()))
        declarations.append(' {"%s",%u,%u,%u,%u,UINT64_C(0x%016x),UINT64_C(0x%016x)},' %
                            (text, ox, oy, w, h, fnv(text.encode()), fnv(payload)))
    manifest = dict(format='SMR1', header_bytes=128, runs=records, payload_bytes=payload_bytes,
        source=dict(file='DejaVuSans-Bold.ttf', sha256=FONT_SHA, license='LICENSE-DejaVu.txt'),
        rasterizer=dict(pillow=PIL.__version__, freetype=features.version('freetype2'),
                        raqm=features.version('raqm'), preview_supersample=scale),
        planes='alpha8 then role8; role zero iff alpha zero, otherwise 12..15',
        shadow_output_offset=[8, 8], runtime='Optional per-run sibling of SFN1; root menu only; no runtime FreeType')
    (destination / 'shop-menu-font-v1.json').write_text(json.dumps(manifest, indent=2) + '\n')
    pins.write_text('/* SPDX-License-Identifier: GPL-2.0-or-later */\n'
        '/* Generated by scripts/export_shop_menu_font.py. Native output pixels. */\n'
        f'#define PF_MENU_BYTES {payload_bytes}\n'
        'static const struct PfMenuSpec menu_spec[7]={\n' + '\n'.join(declarations) + '\n};\n')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=ASSETS)
    parser.add_argument('--pins', type=Path, default=ROOT / 'src/shop_menu_font_pins.h')
    args = parser.parse_args()
    export(args.out, args.pins)
