#!/usr/bin/env python3
"""Verify/rederive identity-only NEWSHF prototype pins; never emit game bytes or HDA.

Default --check needs only the frozen source bundle and committed header.
--game-data additionally verifies original bytes and reproduces the header in
memory. --write requires --game-data and writes only the named pins header.
Runtime FNV64 stamps are integrity witnesses, not cryptographic authentication.
"""
import argparse
import hashlib
from pathlib import Path
import sys
from check_newshf_phase_a import IDENTITY, DEFAULT, check, require

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'src/newshf_prototype_pins.h'
PALETTE_SHA256 = 'f628396306805387f07f72c4ccf0fdee9ca84b8e70ae23ba4ec58ec5fb362da0'
HEADER_SHA256 = '6b111c2b6c1d560d3698e822cf749aa55172849dcab53dfc20ceb5cd3fb85605'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def fnv64(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value


def decode(bank, index):
    """Bounds-checked native 12x14 RLE decode: indices followed by coverage."""
    require(type(index) is int and index > 0 and index * 2 <= len(bank), 'tile index')
    pos = int.from_bytes(bank[(index-1)*2:index*2], 'little')
    pixels, mask, cell = bytearray(168), bytearray(168), 0
    for _ in range(len(bank)):
        require(pos < len(bank), 'truncated tile')
        command = bank[pos]
        pos += 1
        if command == 15:
            return bytes(pixels + mask)
        cell += command & 15
        for _ in range(command >> 4):
            require(cell < 168 and pos < len(bank), 'tile overflow/truncation')
            pixels[cell], mask[cell] = bank[pos], 255
            cell += 1
            pos += 1
    raise ValueError('unterminated tile')


def derive(bank, table, palette):
    require(len(bank) == IDENTITY['bank_size'] and sha(bank) == IDENTITY['bank_sha256'], 'original bank pin')
    require(sha(table) == IDENTITY['item_table_sha256'], 'item table pin')
    require(sha(palette) == PALETTE_SHA256, 'palette file pin')
    records = []
    for rec in IDENTITY['records']:
        raw = table[rec['offset']:rec['offset']+rec['size']]
        require(len(raw) == 77 and sha(raw) == rec['sha256'], '77-byte record pin')
        records.append(fnv64(raw))
    tiles = sorted({base+q for rec in IDENTITY['records'] for base in rec['bases'] for q in IDENTITY['component_offsets']})
    colors = palette[5*768:6*768]
    require(len(colors) == 768 and max(colors) < 64, 'palette5 six-bit geometry')
    rgb = bytes((v << 2) | (v >> 4) for v in colors)
    lines = [
        '/* SPDX-License-Identifier: GPL-2.0-or-later',
        ' * Generated by scripts/build_newshf_prototype_pins.py from SHA-256-verified',
        ' * private original data. Hashes/identity only; no source pixels or records.',
        ' * Runtime FNV64 stamps detect drift, not cryptographic authentication.',
        ' * Identity-only opt-in prototype: no rendering eligibility granted. */',
        '#ifndef NEWSHF_PROTOTYPE_PINS_H', '#define NEWSHF_PROTOTYPE_PINS_H', '#include <stdint.h>',
        '#define NEWSHF_PROTOTYPE_BANK_BYTES 33543u',
        f'#define NEWSHF_PROTOTYPE_BANK_FNV UINT64_C(0x{fnv64(bank):016x})',
        f'#define NEWSHF_PROTOTYPE_BANK_SHA256 "{IDENTITY["bank_sha256"]}"',
        f'#define NEWSHF_PROTOTYPE_TABLE_SHA256 "{IDENTITY["item_table_sha256"]}"',
        f'#define NEWSHF_PROTOTYPE_PALETTE_SHA256 "{PALETTE_SHA256}"',
        'static const unsigned newshf_prototype_record_ids[3] = {163u,167u,168u};',
        'static const uint64_t newshf_prototype_record_fnv[3] = {' + ','.join(f'UINT64_C(0x{x:016x})' for x in records) + '};',
        'static const unsigned newshf_prototype_bases[3][3] = {{125u,123u,127u},{3u,1u,5u},{55u,17u,93u}};',
        'static const struct {unsigned index; uint64_t fnv;} newshf_prototype_tiles[] = {',
    ]
    lines.extend(f' {{{index}u,UINT64_C(0x{fnv64(decode(bank,index)):016x})}},' for index in tiles)
    lines.extend(['};', '/* Palette5: FNV64 of 768 expanded RGB bytes, index order, R/G/B. */',
                  f'#define NEWSHF_PROTOTYPE_PALETTE_FNV UINT64_C(0x{fnv64(rgb):016x})',
                  '#endif', ''])
    return '\n'.join(lines).encode()


def verify(header=HEADER, source=DEFAULT, game_data=None):
    check(source)
    header = Path(header)
    require(header.is_file() and not header.is_symlink(), 'missing/unsafe prototype pins header')
    actual = header.read_bytes()
    require(sha(actual) == HEADER_SHA256, 'frozen prototype pins header drift')
    if game_data is not None:
        game_data = Path(game_data)
        expected = derive(*( (game_data/name).read_bytes() for name in ('newshf.shp','tyrian.hdt','palette.dat')))
        require(actual == expected, 'private source/header reproduction mismatch')
    return dict(status='PASS', scope='identity-only-no-rendering', header_sha256=sha(actual),
                original_bytes_verified=game_data is not None)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--game-data', type=Path)
    p.add_argument('--check', action='store_true', help='read-only check (default)')
    p.add_argument('--write', action='store_true', help='regenerate pinned header from verified private bytes')
    a = p.parse_args()
    try:
        if a.write:
            require(not a.check and a.game_data is not None, '--write requires --game-data and excludes --check')
            check()
            data = derive(*((a.game_data/name).read_bytes() for name in ('newshf.shp','tyrian.hdt','palette.dat')))
            require(sha(data) == HEADER_SHA256, 'generated header differs from reviewed pin')
            require(not HEADER.is_symlink(), 'unsafe header symlink')
            HEADER.write_bytes(data)
        import json
        print(json.dumps(verify(game_data=a.game_data), sort_keys=True))
    except (OSError, ValueError) as exc:
        print('NEWSHF prototype pins failed: '+str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
