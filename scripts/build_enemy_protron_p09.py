#!/usr/bin/env python3
"""Reproduce selected B from the existing approved master, never clip its alpha.

Identity and artistic recipe are separate files. This bounded builder accepts only
this reviewed recipe. --check writes nothing; --apply writes only new P09 outputs.
Sparse reads resolve tracked absent files through Git, never alternate artwork.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import struct
import subprocess
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = 'assets/hd/enemy-protron-p09-v1'
HEADER = 'src/current_enemy_protron_payload_pins.h'
MASTER = 'assets/hd/artwork/player-protron-three-v1/sources/generated-master.png'
MASTER_SHA = '81ae61eaa6d151d333c819d9bcbeaa1f1c299a2ab709ce817738f0527a517479'
PNG_SHA = '0f2d0e268d21fe3a49482d7abdaf0df4e9e0f5101657e0739646619780b71b3a'
RGBA_SHA = '666074b187670c691f63c718a2cea078b84b1172c8b635d5e0c451e4690a956e'
IDENTITY = dict(schema='enemy-protron-p09-identity-v1', material_role=147,
    material_identity=1470227, draw_role=146, frame=227, bank=8,
    logical_size=[12,14], density=8, anchor=[0,0],
    resource_file='enemy-protron-p09-227-8.hda',
    source_indexed_sha256='6ea080e20b3e49fd46a19a8534559be1bad15297e5c29d51ad0a9093efc11b56',
    source_coverage_sha256='7c532bb268ec028bebf06c7f73b373029aafc4980d08d8329c8dd9e258879364',
    eligible_profiles=[[3,1,133,1,141],[3,1,129,1,134]], player_eligibility=False)
RECIPE = dict(schema='enemy-protron-p09-selected-b-recipe-v1',
    source_master_path=MASTER, source_master_sha256=MASTER_SHA,
    source_crop_xyxy=[651,38,1373,762], target_cell_size_px=[56,56],
    canvas_px=[96,112], composite_xy=[16,24],
    resample='Pillow Image.Resampling.LANCZOS',
    alpha_operation='preserve straight RGBA; no mask, threshold, painting or quantization',
    source_png='source227.png', png_sha256=PNG_SHA, rgba_sha256=RGBA_SHA,
    fractional_alpha_pixels=2552, outside_original_mask_nonzero_alpha_pixels=2)

def sha(b): return hashlib.sha256(b).hexdigest()
def fnv(b):
    h=0xcbf29ce484222325
    for v in b: h=((h^v)*0x100000001b3)&((1<<64)-1)
    return h

def read(root,name):
    p=root/name
    if p.is_symlink(): raise ValueError('Symlink input: '+name)
    if p.is_file(): return p.read_bytes()
    return subprocess.check_output(['git','show','HEAD:'+name],cwd=root)

def derive(root=ROOT):
    if json.loads(read(root,DIRECTORY+'/identity.json')) != IDENTITY:
        raise ValueError('Immutable P09 identity changed')
    if json.loads(read(root,DIRECTORY+'/recipe.json')) != RECIPE:
        raise ValueError('Unreviewed P09 selected-B recipe')
    raw=read(root,MASTER)
    if sha(raw)!=MASTER_SHA: raise ValueError('Approved source master changed')
    master=Image.open(io.BytesIO(raw))
    if master.mode!='RGBA' or master.size!=(2011,782): raise ValueError('Master format changed')
    image=Image.new('RGBA',(96,112))
    image.alpha_composite(master.crop((651,38,1373,762)).resize((56,56),Image.Resampling.LANCZOS),(16,24))
    rgba=image.tobytes()
    if sha(rgba)!=RGBA_SHA: raise ValueError('Selected RGBA mismatch; diagnose Pillow, do not repin')
    alpha=rgba[3::4]
    if sum(0<a<255 for a in alpha)!=2552 or image.getbbox()!=(16,24,72,80):
        raise ValueError('Selected soft alpha changed')
    # Original support is evidence only; never applied to artwork.
    rows=['............']*3+['...#####....']+['..#######...']*5+['...#####....']+['............']*4
    outside=sum(a!=0 and rows[(i//96)//8][(i%96)//8]!='#' for i,a in enumerate(alpha))
    if outside!=2: raise ValueError('Outside-support soft samples changed')
    buf=io.BytesIO();image.save(buf,format='PNG');png=buf.getvalue()
    if sha(png)!=PNG_SHA: raise ValueError('PNG encoding mismatch; diagnose Pillow, do not repin')
    hda=struct.pack('<4s6I',b'HDR1',1470227,8,12,14,0,0)+rgba
    header=('/* Generated by build_enemy_protron_p09.py; identity stays private. */\n'
        '#ifndef CURRENT_ENEMY_PROTRON_PAYLOAD_PINS_H\n#define CURRENT_ENEMY_PROTRON_PAYLOAD_PINS_H\n'
        '#include <stdint.h>\n#define CURRENT_ENEMY_PROTRON_1470227_RGBA UINT64_C(0x%016x)\n#endif\n')%fnv(rgba)
    return {DIRECTORY+'/source227.png':png,
            DIRECTORY+'/enemy-protron-p09-227-8.hda':hda,HEADER:header.encode()}

def input_paths(root):
    derive(root)
    return {MASTER,HEADER}|{DIRECTORY+'/'+n for n in ('identity.json','recipe.json','source227.png','enemy-protron-p09-227-8.hda')}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,default=ROOT)
    mode=p.add_mutually_exclusive_group(required=True);mode.add_argument('--check',action='store_true');mode.add_argument('--apply',action='store_true')
    a=p.parse_args();outputs=derive(a.root)
    for name,raw in outputs.items():
        target=a.root/name
        if a.apply:
            if target.is_symlink(): raise ValueError('Symlink output: '+name)
            target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(raw)
        elif read(a.root,name)!=raw: raise ValueError('Derived output differs: '+name)
    print(json.dumps({'status':'PASS','mode':'apply' if a.apply else 'check','outputs':{k:sha(v) for k,v in outputs.items()},'master_copied':False,'old_art_written':False,'new_player_eligibility':False}))
if __name__=='__main__': main()
