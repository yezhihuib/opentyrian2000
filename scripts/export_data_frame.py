"""Pack the reviewed Data-only frame without changing its source artwork.

Pillow 12.3.0 is the reproducibility reference. The source v3 PNG is immutable.
Only resource alpha outside an explicitly bounded two-logical-cell source
support guard is clipped. This DFM1 geometry rule is independent of PSP1.
No native game data, portraits, font sources, or selected HD packs are copied.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/data-frame-v1'
SOURCE_SHA = '34c464d5a05d0dd091a4d1cb3a11d53567ab094768bdb8253b27fcd35d53904d'
MASK_SHA = '9cf12bc96e544f8f00c78e03f9635dc67164ccb82433847dcac43f2e09544211'
PMF_SHA = '639f0c723e1058628e32b052a9613d09a478ff1d2fb4ce28235a94aaa8235260'
PIC_FNV = 0x45a77a2246c174b9
OPTION_RLE_FNV = 0x3c232016c519ed17
OPTION_INDEX_FNV = 0x03a1b83be967efe2
OPTION_MASK_FNV = 0x2f1faa16b55f7cfc
PALETTE_FNV = 0xdda550ae729ffb73
WIDTH, HEIGHT, DENSITY = 1280, 800, 4
PAYLOAD_BYTES = WIDTH * HEIGHT * 4
OPTION_SIZE = (169, 186)
ANCHOR = (1, 1)
GUARD_LOGICAL = 2


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return value


def checked_bytes(path, expected_sha, expected_bytes=None):
    if path.is_symlink() or not path.is_file():
        raise ValueError('Expected unlinked regular source: ' + str(path))
    if path.stat().st_size > 8 * 1024 * 1024:
        raise ValueError('Oversized source: ' + str(path))
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_sha:
        raise ValueError('Source SHA256 mismatch: ' + str(path))
    if expected_bytes is not None and len(data) != expected_bytes:
        raise ValueError('Source size mismatch: ' + str(path))
    return data


def decode_pmf(data):
    """Decode accepted PMF1 samples exactly; no normalization or repainting."""
    if data[:4] != b'PMF1' or len(data) < 128:
        raise ValueError('Expected accepted PMF1')
    fields = struct.unpack_from('<15I', data, 4)
    version, lw, lh, density, width, height, runs, pixels, size = fields[:9]
    if (version, lw, lh, density, width, height) != (1, 320, 200, 4, WIDTH, HEIGHT):
        raise ValueError('Unexpected PMF1 geometry')
    if len(data) != 128 + size or fnv(data[128:]) != struct.unpack_from('<Q', data, 80)[0]:
        raise ValueError('Invalid accepted PMF1 payload')
    raw = bytearray(PAYLOAD_BYTES)
    position, previous_end, count = 128, 0, 0
    for _ in range(runs):
        start, length = struct.unpack_from('<II', data, position)
        position += 8
        end = start + length
        if not length or start < previous_end or end > WIDTH * HEIGHT or start // WIDTH != (end - 1) // WIDTH:
            raise ValueError('Invalid accepted PMF1 run')
        raw[start * 4:end * 4] = data[position:position + length * 4]
        position += length * 4
        previous_end = end
        count += length
    if position != len(data) or count != pixels:
        raise ValueError('Invalid accepted PMF1 run inventory')
    return raw


def local_support(mask):
    if len(mask) != 64000 or set(mask) != {0, 1}:
        raise ValueError('Expected exact anchored binary source support')
    local = bytearray(169 * 186)
    for y in range(200):
        for x in range(320):
            value = mask[y * 320 + x]
            if 1 <= x < 170 and 1 <= y < 187:
                local[(y - 1) * 169 + x - 1] = value
            elif value:
                raise ValueError('Source support outside fixed OPTION20 canvas')
    if fnv(bytes(value * 255 for value in local)) != OPTION_MASK_FNV:
        raise ValueError('Exact source OPTION20 mask authentication failed')
    return bytes(local)


def packed_support(local):
    bits = bytearray((len(local) + 7) // 8)
    for index, value in enumerate(local):
        if value:
            bits[index >> 3] |= 1 << (index & 7)
    if len(bits) != 3930 or bits[-1] & 0xfc:
        raise ValueError('Unexpected packed source-mask geometry')
    return bytes(bits)


def pins_text(payload, whole, local):
    bits = packed_support(local)
    lines = [
        '/* SPDX-License-Identifier: GPL-2.0-or-later */',
        '/* Generated by scripts/export_data_frame.py; do not hand-edit. */',
        '/* OPTION20 source layout is validation/underlay geometry, not HD artwork. */',
        '#ifndef DATA_FRAME_PINS_INC', '#define DATA_FRAME_PINS_INC',
        f'#define DATA_FRAME_PAYLOAD_FNV UINT64_C(0x{fnv(payload):016x})',
        f'#define DATA_FRAME_FILE_FNV UINT64_C(0x{fnv(whole):016x})',
        f'#define DATA_FRAME_PALETTE_FNV UINT64_C(0x{PALETTE_FNV:016x})',
        f'#define DATA_FRAME_OPTION_MASK_FNV UINT64_C(0x{OPTION_MASK_FNV:016x})',
        f'#define DATA_FRAME_SUPPORT_BITS_FNV UINT64_C(0x{fnv(bits):016x})',
        '#define DATA_FRAME_HEADER_BYTES 128u',
        '#define DATA_FRAME_PAYLOAD_BYTES 4096000u',
        '#define DATA_FRAME_FILE_BYTES 4096128u',
        '/* Local bit index = y*169+x, LSB first; final six padding bits are zero. */',
        'static const unsigned char data_frame_option_support[3930] = {',
    ]
    for offset in range(0, len(bits), 16):
        lines.append('    ' + ', '.join(f'0x{value:02x}' for value in bits[offset:offset + 16]) + ',')
    return '\n'.join(lines + ['};', '#endif', ''])


def export(destination, pins, preview=None):
    checked_bytes(ASSETS / 'source-v3.png', SOURCE_SHA, 701041)
    mask = checked_bytes(ASSETS / 'option20-source-support-320x200.bin', MASK_SHA, 64000)
    local = local_support(mask)
    pmf = decode_pmf(checked_bytes(ROOT / 'assets/shop-frame-v1/shop-frame-metal-v1.hda', PMF_SHA, 1276948))
    source = Image.open(ASSETS / 'source-v3.png')
    if source.mode != 'RGBA' or source.size != (676, 744):
        raise ValueError('Expected unmodified normalized v3 RGBA source')

    # Every source write owns a cell, including writes that leave the same
    # color. Preserve PMF samples only where PIC1 survives the native clear
    # rectangle and OPTION20's exact opaque mask. No rectangular approximation.
    surviving = bytearray(64000)
    for y in range(200):
        for x in range(320):
            survives = not (1 <= x < 146 and 1 <= y < 171) and not mask[y * 320 + x]
            surviving[y * 320 + x] = survives
            if not survives:
                for hd_y in range(y * 4, y * 4 + 4):
                    start = (hd_y * WIDTH + x * 4) * 4
                    pmf[start:start + 16] = bytes(16)

    # Resource geometry only: zero the faint generated residue outside the
    # exact source support dilated by 8 HD pixels in Chebyshev distance. The
    # retained PNG is never saved or modified, and all allowed samples remain
    # byte-identical. This does not change PSP1's separate one-cell contract.
    allowed = Image.frombytes('L', OPTION_SIZE, bytes(value * 255 for value in local))
    allowed = allowed.resize(source.size, Image.Resampling.NEAREST)
    allowed = allowed.filter(ImageFilter.MaxFilter(GUARD_LOGICAL * DENSITY * 2 + 1)).tobytes()
    candidate = bytearray(source.tobytes())
    clipped = clipped_opaque = clipped_alpha = 0
    for index, supported in enumerate(allowed):
        if not supported:
            alpha = candidate[index * 4 + 3]
            clipped += bool(alpha)
            clipped_opaque += alpha > 127
            clipped_alpha += alpha
            candidate[index * 4:index * 4 + 4] = bytes(4)
    base = Image.frombytes('RGBA', (WIDTH, HEIGHT), bytes(pmf))
    base.alpha_composite(Image.frombytes('RGBA', source.size, bytes(candidate)), (4, 4))
    payload = base.tobytes()
    fields = [1, 320, 200, DENSITY, WIDTH, HEIGHT, PAYLOAD_BYTES,
              169, 186, ANCHOR[0], ANCHOR[1], GUARD_LOGICAL, 0, 0, 0]
    header = b'DFM1' + struct.pack('<15I', *fields)
    header += struct.pack('<8Q', PIC_FNV, OPTION_RLE_FNV, OPTION_INDEX_FNV,
                          OPTION_MASK_FNV, PALETTE_FNV, fnv(payload), 0, 0)
    whole = header + payload
    if len(header) != 128 or len(payload) != PAYLOAD_BYTES:
        raise ValueError('Unexpected DFM1 output geometry')
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(whole)
    pins.parent.mkdir(parents=True, exist_ok=True)
    pins.write_text(pins_text(payload, whole, local), encoding='ascii')
    manifest = {
        'schema': 'data-frame-resource-v1', 'format': 'DFM1 full-canvas straight RGBA8',
        'version': 1, 'header_bytes': 128, 'logical_size': [320, 200],
        'density': DENSITY, 'canvas': [WIDTH, HEIGHT], 'option20_size': list(OPTION_SIZE),
        'option20_anchor': list(ANCHOR), 'header_uint32_fields': fields,
        'source': {'file': 'source-v3.png', 'sha256': SOURCE_SHA, 'bytes': 701041,
                   'size': [676, 744], 'modifications': 'None; copied byte-for-byte from reviewed v3'},
        'pmf1': {'file': 'assets/shop-frame-v1/shop-frame-metal-v1.hda', 'sha256': PMF_SHA,
                 'processing': 'Exact decoded samples reused only in source cells not owned by native clear rectangle or OPTION20 opaque writes'},
        'source_support': {'file': 'option20-source-support-320x200.bin', 'sha256': MASK_SHA,
                           'opaque_pixels': sum(local), 'packed_include_bytes': 3930,
                           'packed_fnv1a64': f'0x{fnv(packed_support(local)):016x}',
                           'pic1_surviving_cells': sum(surviving)},
        'source_identity': {'pic1_fnv1a64': f'0x{PIC_FNV:016x}',
                            'option20_rle_fnv1a64': f'0x{OPTION_RLE_FNV:016x}',
                            'option20_index_fnv1a64': f'0x{OPTION_INDEX_FNV:016x}',
                            'option20_mask_fnv1a64': f'0x{OPTION_MASK_FNV:016x}',
                            'palette_high_rgb_fnv1a64': f'0x{PALETTE_FNV:016x}'},
        'resource_geometry': {'guard_logical_cells': GUARD_LOGICAL, 'metric': 'Chebyshev',
                              'guard_hd_pixels': 8, 'rule_scope': 'This Data DFM1 frame only; PSP1 source projection remains one cell',
                              'outside_guard_alpha_pixels_removed': clipped,
                              'outside_guard_alpha_gt127_pixels_removed': clipped_opaque,
                              'outside_guard_alpha_sum_removed': clipped_alpha,
                              'allowed_candidate_samples': 'Exact source-v3 samples; no paint, forced opacity, smoothing, or recoloring'},
        'payload_bytes': len(payload), 'payload_fnv1a64': f'0x{fnv(payload):016x}',
        'file_bytes': len(whole), 'file_fnv1a64': f'0x{fnv(whole):016x}',
        'file_sha256': hashlib.sha256(whole).hexdigest(), 'reference_pillow': '12.3.0',
        'runtime': 'Independent optional --data-frame-assets directory; Data menus7/8 only; native faces and dynamic content remain live',
        'license_and_provenance': 'DATA-FRAME-PROVENANCE.txt',
    }
    destination.with_suffix('.json').write_text(json.dumps(manifest, indent=2) + '\n')
    if preview:
        preview.parent.mkdir(parents=True, exist_ok=True)
        base.save(preview)
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ASSETS / 'data-frame-v1.hda')
    parser.add_argument('--pins', type=Path, default=ROOT / 'src/data_frame_pins.inc')
    parser.add_argument('--preview', type=Path, help='Optional development preview, not a renderer capture')
    args = parser.parse_args()
    try:
        export(args.out, args.pins, args.preview)
    except (OSError, ValueError, struct.error) as error:
        parser.exit(1, 'Data frame export refused: ' + str(error) + '\n')
