#!/usr/bin/env python3
"""Finite NEWSHF nine-pose compiler: unchanged selected RGBA pixels to HDR1.

This separate opt-in family does not modify the accepted global registry or
reinterpret source bank/base IDs as material IDs. `check` never writes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from PIL import Image
from check_newshf_phase_a import check, read_json, IDENTITY
from package_runtime import contained_file

INPUT = 'authoring-inputs/enemies/newshf-phase-a'
OUTPUT = 'assets/hd/newshf-v1'
MANIFEST = OUTPUT + '/manifest.json'
HEADER = 'src/newshf_hd_assets.h'
IDS = tuple(range(2100000, 2100009))
PAIRS = tuple((r['record'], b) for r in IDENTITY['records'] for b in r['bases'])

def name(identity):
    if type(identity) is not int or identity not in IDS:
        raise ValueError('Unknown NEWSHF HD role')
    return f'newshf-role{identity}-8.hda'

def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value

def encoded(value):
    return (json.dumps(value, indent=2, sort_keys=True) + '\n').encode()

def derive(root):
    contained_file(root, INPUT + '/manifest.json')
    contained_file(root, INPUT + '/provenance.json')
    check(root / INPUT)
    selected = read_json(root / INPUT / 'manifest.json')
    outputs, rows, declarations = {}, [], []
    for identity, (record, base), art in zip(IDS, PAIRS, selected['art']):
        with Image.open(contained_file(root, INPUT + '/' + art['file'])) as image:
            pixels = image.tobytes()
        raw = b'HDR1' + struct.pack('<6I', identity, 8, 24, 28, 6, 7) + pixels
        source = OUTPUT + '/' + name(identity)
        relative = 'newshf/' + name(identity)
        outputs[source] = raw
        rows.append(dict(identity=identity, record=record, base=base,
                         source_path=source, destination='assets/global/' + relative,
                         source_png=INPUT + '/' + art['file'],
                         source_png_sha256=art['art_sha256'], bytes=len(raw),
                         sha256=hashlib.sha256(raw).hexdigest(), payload_fnv=f'{fnv(pixels):016x}'))
        declarations.append(f' {{{identity}u,{len(raw)}u,8u,24u,28u,6,7,"{relative}",UINT64_C(0x{fnv(pixels):016x})}},')
    outputs[MANIFEST] = encoded(dict(schema='opentyrian-newshf-hd-nine-v1',
        source_contract=INPUT + '/manifest.json', identity=IDENTITY,
        scope='Independent default-off finite NEWSHF compositor; no global registry eligibility', resources=rows))
    outputs[HEADER] = ('/* Generated by scripts/build_newshf_hd.py; unchanged selected pixels. */\n'
        '#ifndef NEWSHF_HD_ASSETS_H\n#define NEWSHF_HD_ASSETS_H\n'
        '#include "global_asset_registry.h"\n'
        'enum { NEWSHF_HD_RESOURCE_COUNT = 9 };\n'
        'static const GlobalAssetResource newshf_hd_resources[NEWSHF_HD_RESOURCE_COUNT] = {\n'
        + '\n'.join(declarations) + '\n};\n#endif\n').encode()
    return outputs

def input_paths(root):
    check(root / INPUT)
    selected = read_json(root / INPUT / 'manifest.json')
    return {INPUT + '/' + a['file'] for a in selected['art']} | {
        INPUT + '/manifest.json', INPUT + '/provenance.json', INPUT + '/report.json', MANIFEST, HEADER} | {
        OUTPUT + '/' + name(i) for i in IDS}

def load(root):
    outputs = derive(root)
    for relative, expected in outputs.items():
        path = contained_file(root, relative)
        if not path.is_file() or path.read_bytes() != expected:
            raise ValueError('Stale/malformed NEWSHF generated consumer: ' + relative)
    actual = {p.name for p in (root / OUTPUT).iterdir()}
    if actual != {'manifest.json'} | {name(i) for i in IDS}:
        raise ValueError('Unexpected NEWSHF resource member')
    rows = json.loads(outputs[MANIFEST])['resources']
    return {r['destination']: r for r in rows}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('build', 'check'))
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    if args.mode == 'build':
        outputs = derive(args.root)
        for relative, raw in outputs.items():
            path = contained_file(args.root, relative)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    print(json.dumps(dict(status='PASS', resources=len(load(args.root)), scope='nine unchanged selected poses')))

if __name__ == '__main__':
    main()
