#!/usr/bin/env python3
"""Export the one reviewed, optional shop OPTION[31] PSP1 resource.

Original game data remains an external input. No original game art is saved.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct
from PIL import Image, ImageChops, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/shop-talon-v1'
SOURCE_SHA = '62b83ef444e0c767cb41f5d087d09f6f5e236533049a48f8f20c7b7347766476'
RLE_HASH, INDEX_HASH, MASK_HASH = 0x1cdda2674a130af2, 0x46b339e8cc2fd434, 0xcdbc751beacea75c


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return value


def original_support(data):
    raw = (data / 'tyrian.shp').read_bytes()
    offset = struct.unpack_from('<I', raw, 2 + 5 * 4)[0]
    count = struct.unpack_from('<H', raw, offset)[0]
    offset += 2
    for sid in range(count):
        present = raw[offset]
        offset += 1
        if not present:
            continue
        w, h, size = struct.unpack_from('<HHH', raw, offset)
        offset += 6
        rle = raw[offset:offset + size]
        offset += size
        if sid != 31:
            continue
        assert (w, h, size) == (85, 112, 5578) and fnv(rle) == RLE_HASH
        index, mask = bytearray(w * h), bytearray(w * h)
        x = y = k = 0
        while k < size:
            v = rle[k]
            k += 1
            if v == 255:
                x += rle[k]
                k += 1
            elif v == 254:
                x = w
            elif v == 253:
                x += 1
            else:
                assert x < w and y < h
                index[y * w + x], mask[y * w + x] = v, 255
                x += 1
            assert x <= w
            if x == w:
                x, y = 0, y + 1
        assert x == 0 and y <= h
        assert fnv(index) == INDEX_HASH and fnv(mask) == MASK_HASH
        return Image.frombytes('L', (w, h), bytes(mask))
    raise ValueError('Missing OPTION[31]')


def export(data, destination):
    source = ASSETS / 'source-imagegen.png'
    assert hashlib.sha256(source.read_bytes()).hexdigest() == SOURCE_SHA
    original = Image.open(source).convert('RGBA')
    assert original.size == (1093, 1439)
    rgba = original.crop((0, 0, 1093, 1390)).resize((340, 448), Image.Resampling.LANCZOS)
    raw = bytearray(rgba.tobytes())
    removed = sum(0 < raw[p + 3] < 8 for p in range(0, len(raw), 4))
    for p in range(0, len(raw), 4):
        if raw[p + 3] < 8:
            raw[p:p + 4] = bytes(4)
    rgba = Image.frombytes('RGBA', rgba.size, bytes(raw))
    # Validation only: the original binary mask never clips the new contour.
    support = original_support(data).resize((340, 448), Image.Resampling.NEAREST)
    allowed = support.filter(ImageFilter.MaxFilter(9))
    excess = ImageChops.subtract(rgba.getchannel('A').point(lambda a: 255 if a else 0), allowed)
    outside = sum(bool(v) for v in excess.tobytes())
    assert outside == 0, f'{outside} authored samples exceed the one-logical-pixel contour limit; bbox={excess.getbbox()}'
    payload_hash = fnv(raw)
    fields = [1, 5, 31, 85, 112, 4, 340, 448, 35, 33, len(raw), 4, 1, 1, 0]
    header = b'PSP1' + struct.pack('<15I', *fields)
    header += struct.pack('<8Q', 0x45a77a2246c174b9, 0x1c6687307999bd82,
                          RLE_HASH, INDEX_HASH, MASK_HASH, payload_hash, 0, 0)
    assert len(header) == 128 and len(raw) == 609280
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(header + raw)
    rgba.save(destination.with_suffix('.png'))
    manifest = dict(format='PSP1', header_bytes=128, source=dict(file='source-imagegen.png',
        sha256=SOURCE_SHA, size=[1093, 1439], crop_xyxy=[0, 0, 1093, 1390],
        provenance='OpenAI imagegen exec-33bfe602-3004-4c52-b55b-79ee48a8cdbd'),
        normalization='Original RGBA crop -> 340x448 Lanczos; no original-mask clipping',
        alpha_below_8_zeroed_samples=removed, outside_one_logical_pixel_samples=outside,
        logical_size=[85,112], density=4, anchor=[35,33], rgba='straight RGBA8; transparent RGB is zero',
        payload_bytes=len(raw), payload_fnv1a=f'0x{payload_hash:016x}',
        file_sha256=hashlib.sha256(header+raw).hexdigest(), pillow=Image.__version__,
        original_rle_fnv1a=f'0x{RLE_HASH:016x}', original_index_fnv1a=f'0x{INDEX_HASH:016x}',
        original_mask_fnv1a=f'0x{MASK_HASH:016x}',
        runtime='Independent optional sibling of SFN1 resources in --startup-assets')
    destination.with_suffix('.json').write_text(json.dumps(manifest, indent=2)+'\n')
    pins = ROOT / 'src/shop_talon_sprite_pins.h'
    pins.write_text('/* SPDX-License-Identifier: GPL-2.0-or-later */\n'
        '/* Generated by scripts/export_shop_sprite.py from the reviewed PSP1 candidate. */\n'
        f'#define PF_SPRITE_RLE UINT64_C(0x{RLE_HASH:016x})\n'
        f'#define PF_SPRITE_INDEX UINT64_C(0x{INDEX_HASH:016x})\n'
        f'#define PF_SPRITE_MASK UINT64_C(0x{MASK_HASH:016x})\n'
        f'#define PF_SPRITE_HASH UINT64_C(0x{payload_hash:016x})\n')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--data', type=Path, required=True)
    parser.add_argument('--out', type=Path, default=ASSETS / 'shop-talon-option31-v1.hda')
    args = parser.parse_args()
    export(args.data, args.out)
