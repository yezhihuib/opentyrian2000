"""Deterministically pack all18 approved Data portraits without changing samples."""
from pathlib import Path
import argparse,hashlib,json,struct
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/data-portrait-v1'
COUNT=18
SIZES=((65,55),)*4+((65,53),)+((65,55),)*7+((69,64),(70,63),(70,59),(70,77),(69,71),(48,63))
PALETTES=(1,2,3,4,6,9,11,12,16,13,14,15,0,0,0,0,0,0)
PILOT_SHA='646237fab8e96ae5c2400a098aec8c76f19f6e37b1610919faf2fd18213ad7ad'
PILOT_RESOURCE_SHA='9c861bd247753c3801ee73fd1fe2e8bf518a27550b58b01d311da3d815b450aa'

def fnv(data):
 h=14695981039346656037
 for b in data:h=((h^b)*1099511628211)&0xffffffffffffffff
 return h

def sources():
 path=ASSETS/'source-pack.json'
 if path.is_symlink() or not path.is_file() or path.stat().st_size>1024*1024:raise ValueError('Expected bounded regular source manifest')
 manifest=json.loads(path.read_text());rows=manifest['portraits']
 if len(rows)!=COUNT or [r['runtime_id'] for r in rows]!=list(range(COUNT)):raise ValueError('Expected ordered complete18-face allowlist')
 for face,row in enumerate(rows):
  w,h=SIZES[face];x,y=77-w//2,92-h//2
  if row['bank']!=4 or row['source_id_1based']!=face+1 or row['size']!=[w,h] or row['anchor']!=[x,y] or row['palette_index']!=PALETTES[face] or row['canonical_1280_export_size']!=[w*4,h*4] or row['canonical_1280_anchor']!=[x*4,y*4]:raise ValueError('Native source geometry/palette mismatch')
  if not 0<row['rle_bytes']<=w*h*3:raise ValueError('Source RLE bounds')
  name=row['approved_png']
  if Path(name).name!=name or not name.startswith(f'source-face{face:02d}-v') or not name.endswith('.png'):raise ValueError('Approved source name')
 return rows

def pack(face,row):
 w,h=SIZES[face];source=ASSETS/row['approved_png']
 if source.is_symlink() or not source.is_file() or source.stat().st_size>1024*1024:raise ValueError('Expected bounded regular approved PNG')
 raw=source.read_bytes()
 if hashlib.sha256(raw).hexdigest()!=row['approved_png_sha256']:raise ValueError('Approved source PNG SHA256 mismatch')
 if face==7 and row['approved_png_sha256']!=PILOT_SHA:raise ValueError('FACE7 pilot changed')
 with Image.open(source) as image:
  if image.mode!='RGBA' or image.size!=(w*4,h*4):raise ValueError('Expected exact native4x RGBA8 approved source')
  payload=image.tobytes()
 fields=(1,320,200,4,w,h,w*4,h*4,*row['anchor'],face,face+1,row['palette_index'],len(payload),0)
 hashes=tuple(int(row[k],16) for k in ('rle_fnv1a64','index_fnv1a64','mask_fnv1a64','effective_palette_rgb_fnv1a64'))
 header=b'DPR1'+struct.pack('<15I',*fields)+struct.pack('<8Q',*hashes,fnv(payload),0,0,0)
 whole=header+payload
 if face==7 and hashlib.sha256(whole).hexdigest()!=PILOT_RESOURCE_SHA:raise ValueError('FACE7 DPR1 resource changed')
 metadata={'schema':'data-portrait-resource-v1','format':'DPR1 bounded straight RGBA8','header_bytes':128,'header_uint32_fields':fields,'source_identity_fnv1a64':[f'{x:016x}' for x in hashes],'source_png_sha256':row['approved_png_sha256'],'payload_fnv1a64':f'{fnv(payload):016x}','file_fnv1a64':f'{fnv(whole):016x}','file_sha256':hashlib.sha256(whole).hexdigest(),'file_bytes':len(whole),'processing':f'Exact approved {w*4}x{h*4} PNG samples, no filtering, paint, mask clipping, recoloring, or alpha changes','composition':'Captured pre-native-face underlay + independently authenticated DFM static contribution + approved face alpha; later native writes/cursor retain full logical ownership'}
 return whole,metadata

def export(output,pins):
 rows=sources();packed=[pack(face,row) for face,row in enumerate(rows)]
 # Prepare and authenticate every input before writing any generated output.
 lines=['/* SPDX-License-Identifier: GPL-2.0-or-later */','/* Generated by scripts/export_data_portrait.py. */','#ifndef DATA_PORTRAIT_PINS_INC','#define DATA_PORTRAIT_PINS_INC','static const struct DPPin dp_pins[DP_COUNT]={']
 for face,(row,(whole,meta)) in enumerate(zip(rows,packed)):
  w,h=SIZES[face];ints=(w,h,*row['anchor'],row['palette_index'],row['rle_bytes'],len(whole)-128)
  hashes=(*struct.unpack_from('<5Q',whole,64),fnv(whole))
  lines.append(' /* FACE%02d */ {%s,%s},'%(face,','.join(map(str,ints)),','.join(f'UINT64_C(0x{h:016x})' for h in hashes)))
 lines+=['};','#endif','']
 output.mkdir(parents=True,exist_ok=True);pins.parent.mkdir(parents=True,exist_ok=True)
 for face,(whole,metadata) in enumerate(packed):
  (output/f'face{face:02d}-v1.hda').write_bytes(whole)
  (output/f'face{face:02d}-v1.json').write_text(json.dumps(metadata,indent=2)+'\n')
 pins.write_text('\n'.join(lines))
 return {'schema':'data-portrait-export-v2','portrait_count':COUNT,'payload_bytes':sum(len(p[0])-128 for p in packed),'resource_bytes':sum(len(p[0]) for p in packed),'resources':[p[1] for p in packed]}

if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path,default=ASSETS);p.add_argument('--pins',type=Path,default=ROOT/'src/data_portrait_pins.inc');a=p.parse_args();print(json.dumps(export(a.output,a.pins),indent=2))
