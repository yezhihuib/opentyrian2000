"""Finite three-pose NEWSHF record165 art, without animation or gameplay edits.

The original24x28 bank10 bases49/47/51 retain anchor6/7. Registered editable
192x224 RGBA masters may use smooth alpha only within fixed native support.
Transparent pixels are canonical RGBA0; native source pixels are not stored.
"""
import io
import struct
from PIL import Image
from current_guided_compatibility import read, parse, sha, image
from build_newshf_hd import fnv

INPUT_ROOT='authoring-inputs/newshf-fighter165'
ROOT='assets/hd/current-compat/newshf-fighter165'
HEADER='src/current_fighter165_newshf_hd_assets.h'
SELECTION='assets/hd/authoring/newshf-fighter165.json'
MAPPING='packaging/current-fighter165-newshf-compatibility.json'
IDS=(2100031,2100032,2100033)
BASES=(49,47,51)
RECORDS=(165,)
SCHEMA='opentyrian-fighter165-newshf-authoring-v1'
MAPPING_SCHEMA='opentyrian-fighter165-newshf-compatibility-v1'
REVISION='current-single-source-fighter165-newshf-three'
MASTER_NAMES=tuple(f'master-base{base}.png' for base in BASES)
MASK_NAMES=tuple(f'native-mask-base{base}.png' for base in BASES)
INPUTS=MASTER_NAMES+MASK_NAMES
MASK_SHA256={49: 'c45e2f2512df707f5f177d9ebc6fbe953194fcf0df5932fff1163e8ac78d9909', 47: 'a25a5c7d1ea2298fb71ef5057267487101997a37d69343f2a5779d562874aa34', 51: '1a4d048f1067923b06de78bdd7283fd75c8a090e212547ef072c52e2eba26597'}
MASK_COUNTS={49:274,47:265,51:263}

def name(identity):
    if type(identity) is not int or identity not in IDS:raise ValueError('Unknown fighter165 identity')
    return f'newshf-role{identity}-8.hda'
def png(identity):return INPUT_ROOT+'/derived/'+name(identity).replace('.hda','.png')
def generated_paths():return {png(identity) for identity in IDS}
def input_paths(root):return {INPUT_ROOT+'/'+n for n in INPUTS}|{SELECTION}
def encode_png(im):
    out=io.BytesIO();im.save(out,format='PNG',optimize=False);return out.getvalue()

def generate(root,raw,candidate=False):
    selected=parse(raw)
    if not isinstance(selected,dict) or set(selected)!={'schema','version','inputs'} or selected['schema']!=SCHEMA:raise ValueError('Invalid fighter165 selection')
    if not isinstance(selected['version'],str) or not 1<=len(selected['version'])<=128:raise ValueError('Invalid fighter165 version')
    expected={INPUT_ROOT+'/'+n for n in INPUTS}
    if not isinstance(selected['inputs'],dict) or set(selected['inputs'])!=expected:raise ValueError('Invalid fixed fighter165 input closure')
    for path,digest in selected['inputs'].items():
        if not isinstance(digest,str) or len(digest)!=64 or sha(read(root,path))!=digest:raise ValueError('Changed fighter165 input: '+path)
    pngs={};blobs={};rows=[]
    for identity,base,master_name,mask_name in zip(IDS,BASES,MASTER_NAMES,MASK_NAMES):
        raw_mask=read(root,INPUT_ROOT+'/'+mask_name)
        if sha(raw_mask)!=MASK_SHA256[base]:raise ValueError('Immutable fighter165 native mask changed')
        mask=Image.open(io.BytesIO(raw_mask));mask.load()
        if mask.mode!='L' or mask.size!=(24,28) or not set(mask.tobytes())<={0,255} or sum(bool(v) for v in mask.tobytes())!=MASK_COUNTS[base]:raise ValueError('Invalid fighter165 native mask')
        master=image(read(root,INPUT_ROOT+'/'+master_name),(192,224))
        enlarged=mask.resize(master.size,Image.Resampling.NEAREST).tobytes()
        pixels=master.tobytes()
        if not any(pixels[3::4]):raise ValueError('Empty fighter165 master')
        for n,covered in enumerate(enlarged):
            pixel=pixels[4*n:4*n+4]
            if (not covered or not pixel[3]) and pixel!=b'\0\0\0\0':raise ValueError('Fighter165 art must be RGBA0 outside support and behind alpha0')
        data=encode_png(master);blob=struct.pack('<4s6I',b'HDR1',identity,8,24,28,6,7)+pixels
        pngs[png(identity)]=data;blobs[identity]=blob
        rows.append(dict(identity=identity,records=list(RECORDS),base=base,source_path=ROOT+'/'+name(identity),destination='assets/global/newshf-fighter165/'+name(identity),source_png=png(identity),source_png_sha256=sha(data),bytes=len(blob),sha256=sha(blob),payload_fnv=f'{fnv(blob[28:]):016x}'))
    return selected,pngs,blobs,rows

def payload_header(rows):
    if tuple(r['identity'] for r in rows)!=IDS or tuple(r['base'] for r in rows)!=BASES:raise ValueError('Invalid fighter165 rows')
    lines=[f' {{{r["identity"]}u,{r["bytes"]}u,8u,24u,28u,6,7,"newshf-fighter165/{name(r["identity"])}",UINT64_C(0x{r["payload_fnv"]})}},' for r in rows]
    return ('/* Generated by build_current_fighter165_newshf.py. */\n#ifndef CURRENT_FIGHTER165_NEWSHF_HD_ASSETS_H\n#define CURRENT_FIGHTER165_NEWSHF_HD_ASSETS_H\n#include "global_asset_registry.h"\nenum { FIGHTER165_NEWSHF_HD_RESOURCE_COUNT = 3 };\nstatic const GlobalAssetResource fighter165_newshf_hd_resources[3] = {\n'+'\n'.join(lines)+'\n};\n#endif\n').encode()

def load(root):
    selected,pngs,blobs,rows=generate(root,read(root,SELECTION))
    if parse(read(root,MAPPING))!=dict(schema=MAPPING_SCHEMA,selection=SELECTION,files=rows):raise ValueError('Fighter165 mapping differs from derived rows')
    for path,data in pngs.items():
        if read(root,path)!=data:raise ValueError('Changed fighter165 derived PNG')
    for identity,data in blobs.items():
        if read(root,ROOT+'/'+name(identity))!=data:raise ValueError('Changed fighter165 transport')
    if read(root,HEADER)!=payload_header(rows):raise ValueError('Changed fighter165 header')
    return {row['destination']:row for row in rows}
