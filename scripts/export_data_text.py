#!/usr/bin/env python3
"""Validate occurrence-bound Chinese Data text and emit bounded runtime resources."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from data_translation_validation import validate_paragraphs


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, required=True)
    parser.add_argument('--translations', type=Path, required=True)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--pins', type=Path, required=True)
    args = parser.parse_args()
    catalog = json.loads(args.catalog.read_text(encoding='utf-8'))
    translations = json.loads(args.translations.read_text(encoding='utf-8'))
    expected = {row['id']: row for row in catalog['entries']}
    rows = translations['entries']
    if len(rows) != len(expected) or len({row['id'] for row in rows}) != len(rows):
        raise ValueError('All 149 occurrence identities must be present exactly once')
    payload = bytearray()
    for row in sorted(rows, key=lambda r: (r['episode'], r['cube_index'])):
        source = expected[row['id']]
        for key in ('episode', 'cube_index', 'source_sha256'):
            if row[key] != source[key]:
                raise ValueError('Source identity mismatch: ' + row['id'])
        validate_paragraphs(source['paragraphs'], row['paragraphs'], row['id'])
        values = [row['title'], row['header'], '\n\n'.join(row['paragraphs'])]
        if any(original.strip() and not translated.strip() for original, translated in zip((source['title'], source['header'], '\n\n'.join(source['paragraphs'])), values)):
            raise ValueError('Empty translation: ' + row['id'])
        encoded = [v.encode('utf-8', errors='strict') for v in values]
        if any(b'\0' in v or len(v) > 16384 for v in encoded):
            raise ValueError('NUL/oversized entry')
        payload += struct.pack('<HHIIIQ', row['episode'], row['cube_index'], *map(len, encoded), int(source['source_fnv1a64'], 16))
        payload += b'\0'.join(encoded) + b'\0'
    binary = struct.pack('<4sIIIQ', b'DZT1', 1, len(rows), len(payload), fnv(payload)) + payload
    if len(binary) > 1024 * 1024:
        raise ValueError('Text exceeds 1 MiB')
    args.output.write_bytes(binary)
    font = args.font.read_bytes()
    pins = ['/* Generated by scripts/export_data_text.py. Do not edit. */',
            '/* Source catalog SHA256: '+hashlib.sha256(args.catalog.read_bytes()).hexdigest()+' */',
            '#define DATA_TEXT_RESOURCE_BYTES %du' % len(binary),
            '#define DATA_TEXT_RESOURCE_FNV UINT64_C(0x%016x)' % fnv(binary),
            '#define DATA_TEXT_FONT_BYTES %du' % len(font),
            '#define DATA_TEXT_FONT_FNV UINT64_C(0x%016x)' % fnv(font),
            'static const struct SourcePin source_pins[] = {']
    for row in catalog['source_files']:
        pins.append(' { %du, %du, UINT64_C(0x%s) },' % (row['episode'], row['bytes'], row['fnv1a64']))
    pins += ['};', 'static const struct EntryPin entry_pins[] = {']
    for row in catalog['entries']:
        pins.append(' { %du, %du, %du, %du, UINT64_C(0x%s), %s },' % (row['episode'], row['cube_index'], row['source_offset'], row['source_end_offset'], row['source_fnv1a64'], 'true' if not row['paragraphs'] else 'false'))
    pins += ['};', '']
    args.pins.write_text('\n'.join(pins), encoding='ascii')
    print(json.dumps({'entries': len(rows), 'text_bytes': len(binary), 'text_sha256': hashlib.sha256(binary).hexdigest(), 'font_bytes': len(font), 'font_sha256': hashlib.sha256(font).hexdigest()}))


if __name__ == '__main__':
    main()
