#!/usr/bin/env python3
"""Export the reviewed code-native shield as a live-palette PSS1 material.

The source silhouette is validation-only. Geometry is independently authored;
no source raster, screenshot, clipping mask or fixed RGB enters the material.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct
import numpy as np
from PIL import Image, ImageChops, ImageFilter
from export_shop_equipment import fnv, support

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/shop-shield-v1'
SP = dict(bank=5, index=26, size=(99, 23), anchor=(28, 23), rle_bytes=678,
          rle=0x2b70bbc97a03a906, index_hash=0xb2954b44fe9312bd, mask=0xb3481df839c0dec8)
ALPHA_FNV = 0x9c0ae0f6a65255c9
ROLE_FNV = 0x747a5079e7a8a3ef
VALUES = [-8, -7, -6, -5, -4, -3, -1, -3, 0, 2, 4]


def geometry():
    """The accepted shallow ribbon and four detached soft endpoints, density 4."""
    y, x = np.mgrid[:92, :396]
    x, y = (x + .5) / 4, (y + .5) / 4
    u = (x - 49.5) / 38.8
    top, bottom = .45 + 12.05*u*u, 6.6 + 7.0*u**4
    thickness = bottom - top
    center = top + thickness/2
    slope = (12.05*u + 14*u**3) / 38.8
    dist = (np.abs(y-center) - thickness/2) / np.sqrt(1+slope*slope)
    signed = np.maximum(dist, np.abs(x-49.5)-38.55)
    alpha = .97 / (1 + np.exp(np.clip(signed/.15, -50, 50)))
    fraction = np.clip((y-top)/np.maximum(thickness, .1), 0, 1)
    role = 11.95 - 2.65*fraction - np.exp(-((fraction-.70)/.14)**2)
    for cx, cy, radius, tone in [(6.5,16.2,1.85,10.0), (1.9,20.7,1.5,9.2),
                                 (92.5,16.2,1.85,10.0), (97.1,20.7,1.5,9.2)]:
        distance = np.sqrt((x-cx)**2 + (y-cy)**2)
        a = .94 / (1 + np.exp(np.clip((distance-radius)/.15, -50, 50)))
        use = a > alpha
        role[use] = tone - 1.5*np.clip(distance[use]/radius, 0, 1)
        alpha = np.maximum(alpha, a)
    alpha = np.clip(np.rint(alpha*255), 0, 255).astype(np.uint8)
    alpha[alpha < 3] = 0
    role = np.where(alpha > 0, np.rint(np.clip(role, 0, 15)*16), 0).astype(np.uint8)
    return alpha, role


def export(data):
    alpha, role = geometry()
    assert fnv(alpha.tobytes()) == ALPHA_FNV and fnv(role.tobytes()) == ROLE_FNV
    allowed = support(data, SP).filter(ImageFilter.MaxFilter(3)).resize((396,92), Image.Resampling.NEAREST)
    outside = sum(bool(v) for v in ImageChops.subtract(Image.fromarray(alpha).point(lambda a: 255 if a else 0), allowed).tobytes())
    assert outside == 0, 'Geometry exceeds the reviewed one-cell source support guard'
    assert np.all(role <= 240) and np.all(role[alpha == 0] == 0)
    payload = alpha.tobytes() + role.tobytes()
    fields = [1,5,26,99,23,4,396,92,28,23,36432,36432,15,4,0]
    header = b'PSS1' + struct.pack('<15I', *fields) + struct.pack('<8Q',
        0x45a77a2246c174b9, 0x1c6687307999bd82, SP['rle'], SP['index_hash'], SP['mask'], fnv(payload), 0, 0)
    assert len(header) == 128 and len(payload) == 72864
    ASSETS.mkdir(exist_ok=True)
    destination = ASSETS / 'shop-shield-option26-v1.hda'
    destination.write_bytes(header + payload)
    (ASSETS / 'shield-alpha8-roleq4-4x.bin').write_bytes(payload)
    Image.fromarray(alpha).save(ASSETS / 'shield-alpha-4x.png')
    Image.fromarray(role).save(ASSETS / 'shield-role-q4-4x.png')
    manifest = dict(format='PSS1', header_bytes=128, provenance='Independent analytic code-native geometry; accepted 2026-10-19',
        bank=5, index=26, logical_size=[99,23], density=4, raster_size=[396,92], anchor=[28,23],
        material='alpha8 followed by Q4 palette role; hue15; adjacent original HV roles mapped before live-palette interpolation; no second fade gain',
        geometry='Shallow continuous warm arc and four detached soft radial endpoints; original mask validates support only',
        source_rle_bytes=678, source_rle_fnv1a=f'0x{SP["rle"]:016x}', source_index_fnv1a=f'0x{SP["index_hash"]:016x}', source_mask_fnv1a=f'0x{SP["mask"]:016x}',
        alpha_fnv1a=f'0x{ALPHA_FNV:016x}', role_fnv1a=f'0x{ROLE_FNV:016x}', payload_bytes=len(payload), payload_fnv1a=f'0x{fnv(payload):016x}',
        file_bytes=len(header+payload), file_sha256=hashlib.sha256(header+payload).hexdigest(),
        nonzero_outside_one_logical_cell=outside, values=VALUES, none_value=-10,
        runtime='Independent optional terminal shield layer in authenticated Talon shop root/category or product categories2/5; all original indexed work remains unchanged')
    destination.with_suffix('.json').write_text(json.dumps(manifest, indent=2)+'\n')
    (ROOT/'src/shop_shield_material_pins.h').write_text(
        '/* SPDX-License-Identifier: GPL-2.0-or-later */\n'
        '/* Generated by scripts/export_shop_shield.py from the reviewed analytic material. */\n'
        f'#define PF_SHIELD_HASH UINT64_C(0x{fnv(payload):016x})\n')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, required=True)
    export(parser.parse_args().data)
