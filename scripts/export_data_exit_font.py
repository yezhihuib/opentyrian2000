#!/usr/bin/env python3
"""Rebuild the optional Data EXIT run using the accepted shop menu typeface."""
from pathlib import Path
import argparse, hashlib, json, struct
from PIL import Image, ImageDraw, ImageFont, features
import PIL
ROOT=Path(__file__).resolve().parents[1]
FONT_SHA='a4c5bc453ca281d90ea079e596da7ae0dfeb5777497c29ec254e76d97ff6f890'
def fnv(data):
 h=14695981039346656037
 for b in data:h=((h^b)*1099511628211)&0xffffffffffffffff
 return h
def export(out,pins):
 font=ROOT/'assets/shop-menu-font-v1/DejaVuSans-Bold.ttf'
 assert hashlib.sha256(font.read_bytes()).hexdigest()==FONT_SHA
 assert PIL.__version__=='12.3.0' and features.version('freetype2')=='2.14.3'
 scale=8;f=ImageFont.truetype(str(font),52*scale)
 l,t,r,b=f.getbbox('EXIT');w=(r-l+scale-1)//scale+2;h=(b-t+scale-1)//scale+2
 mask=Image.new('L',(w*scale,h*scale));ImageDraw.Draw(mask).text((scale-l,scale-t),'EXIT',font=f,fill=255)
 alpha=mask.resize((w,h),Image.Resampling.BOX).tobytes();roles=bytearray(w*h)
 for y in range(h):
  role=15 if y<3.4 else 14 if y<6.1 else 12 if y>=h-3.1 else 13
  for x in range(w):
   if alpha[y*w+x]:roles[y*w+x]=role
 payload=alpha+roles
 raw=b'DEX1'+struct.pack('<7I',1,w,h,52,8,len(payload),0)+struct.pack('<4Q',fnv(payload),0,0,0)+payload
 out.mkdir(parents=True,exist_ok=True);(out/'data-exit-v1.hda').write_bytes(raw)
 manifest=dict(format='DEX1',text='EXIT',width=w,height=h,font_size_1280=52,cap_height_1280=(b-t)/scale,shadow_offset_1280=[8,8],font_source='assets/shop-menu-font-v1/DejaVuSans-Bold.ttf',font_sha256=FONT_SHA,license='assets/shop-menu-font-v1/LICENSE-DejaVu.txt',rasterizer=dict(pillow=PIL.__version__,freetype=features.version('freetype2'),supersample=scale),planes='alpha8 then native gold role8 (12..15)',file_bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest())
 (out/'data-exit-v1.json').write_text(json.dumps(manifest,indent=2)+'\n')
 pins.write_text('/* Generated by scripts/export_data_exit_font.py. */\n#define DATA_EXIT_WIDTH %uu\n#define DATA_EXIT_HEIGHT %uu\n#define DATA_EXIT_BYTES %uu\n#define DATA_EXIT_FNV UINT64_C(0x%016x)\n'%(w,h,len(raw),fnv(raw)))
 print(json.dumps(manifest,indent=2))
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--out',type=Path,default=ROOT/'assets/data-text-zh-CN-v1');p.add_argument('--pins',type=Path,default=ROOT/'src/data_exit_pins.inc');a=p.parse_args();export(a.out,a.pins)
