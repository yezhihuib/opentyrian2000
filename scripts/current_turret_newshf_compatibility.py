"""One generated turret master, exact original peripheral ground, and a 22-cell hot overlay for records162/840.

Two outputs map the native seven slots; no gameplay or animation timing is generated.
"""
import io
import struct
from PIL import Image
from current_guided_compatibility import read, parse, sha, image
from build_newshf_hd import fnv
INPUT_ROOT='authoring-inputs/newshf-turret'
ROOT='assets/hd/current-compat/newshf-turret'
HEADER='src/current_turret_newshf_hd_assets.h'
SELECTION='assets/hd/authoring/newshf-turret.json'
MAPPING='packaging/current-turret-newshf-compatibility.json'
IDS=(2100016,2100017)
SCHEMA='opentyrian-turret-newshf-authoring-v1'
REVISION='current-single-source-turret-newshf-two'
INPUTS=('cold-master.png','hot-overlay.png','native-hot-mask.png','pod-composition-mask8x.png','native-peripheral-source.png')
MASK_SHA256='dfc78c292af41930284952c8710bd3d4ecd054cede78f455bbb48e820f13edce'
MATTE_SHA256='1a51c1bcd9d2556956c7b4998147f1fb76860c6d92f809ec129938f944e7bc44'
PERIPHERAL_SHA256='97fa5547cb13c91dd721f2f095a32856421f25dcf8981f01ed2b7529458fa070'
RECORDS=(162,840)
def name(i):
 if type(i) is not int or i not in IDS:raise ValueError('Unknown turret identity')
 return f'newshf-role{i}-8.hda'
def png(i):return INPUT_ROOT+'/derived/'+name(i).replace('.hda','.png')
def generated_paths():return {png(i) for i in IDS}
def input_paths(root):return {INPUT_ROOT+'/'+n for n in INPUTS}|{SELECTION}
def encode_png(im):
 out=io.BytesIO();im.save(out,format='PNG',optimize=False);return out.getvalue()
def compose_cold(root,cold):
 raw_matte=read(root,INPUT_ROOT+'/pod-composition-mask8x.png')
 raw_peripheral=read(root,INPUT_ROOT+'/native-peripheral-source.png')
 if sha(raw_matte)!=MATTE_SHA256 or sha(raw_peripheral)!=PERIPHERAL_SHA256:raise ValueError('Immutable turret peripheral composition changed')
 matte=Image.open(io.BytesIO(raw_matte)).convert('L')
 if matte.size!=(192,224):raise ValueError('Invalid turret composition matte')
 peripheral=image(raw_peripheral,(24,28)).resize((192,224),Image.Resampling.NEAREST)
 out=bytearray();generated=cold.tobytes();original=peripheral.tobytes()
 for i,w in enumerate(matte.tobytes()):
  g=generated[i*4:i*4+4];o=original[i*4:i*4+4]
  if w<255 and o[3]!=255:raise ValueError('Missing original peripheral pixel')
  out.extend((g[k]*w+o[k]*(255-w)+127)//255 for k in range(3));out.append(255)
 return Image.frombytes('RGBA',(192,224),bytes(out))
def generate(root,raw,candidate=False):
 selected=parse(raw)
 if not isinstance(selected,dict) or set(selected)!={'schema','version','inputs'} or selected['schema']!=SCHEMA:raise ValueError('Invalid turret selection')
 if not isinstance(selected['version'],str) or not 1<=len(selected['version'])<=128:raise ValueError('Invalid turret version')
 expected={INPUT_ROOT+'/'+n for n in INPUTS}
 if not isinstance(selected['inputs'],dict) or set(selected['inputs'])!=expected:raise ValueError('Invalid fixed turret input closure')
 for p,h in selected['inputs'].items():
  if sha(read(root,p))!=h:raise ValueError('Changed turret input: '+p)
 raw_mask=read(root,INPUT_ROOT+'/native-hot-mask.png')
 if sha(raw_mask)!=MASK_SHA256:raise ValueError('Immutable turret native hot mask changed')
 mask=Image.open(io.BytesIO(raw_mask)).convert('L')
 if mask.size!=(24,28) or not set(mask.tobytes())<={0,255} or sum(bool(x) for x in mask.tobytes())!=22:raise ValueError('Invalid turret hot mask')
 cold=image(read(root,INPUT_ROOT+'/cold-master.png'),(192,224))
 overlay=image(read(root,INPUT_ROOT+'/hot-overlay.png'),(192,224))
 if set(cold.getchannel('A').tobytes())!={255}:raise ValueError('Turret background must remain completely opaque')
 enlarged=mask.resize(cold.size,Image.Resampling.NEAREST)
 if any(a and not m for a,m in zip(overlay.getchannel('A').tobytes(),enlarged.tobytes())):raise ValueError('Turret hot overlay leaves original changed cells')
 cold=compose_cold(root,cold)
 hot=Image.alpha_composite(cold,overlay)
 if set(hot.getchannel('A').tobytes())!={255}:raise ValueError('Turret hot frame must remain opaque')
 rows=[];pngs={};blobs={}
 for identity,base,piece in zip(IDS,(39,41),(cold,hot)):
  data=encode_png(piece);blob=struct.pack('<4s6I',b'HDR1',identity,8,24,28,6,7)+piece.tobytes()
  pngs[png(identity)]=data;blobs[identity]=blob
  rows.append(dict(identity=identity,records=list(RECORDS),base=base,source_path=ROOT+'/'+name(identity),destination='assets/global/newshf-turret/'+name(identity),source_png=png(identity),source_png_sha256=sha(data),bytes=len(blob),sha256=sha(blob),payload_fnv=f'{fnv(blob[28:]):016x}'))
 return selected,pngs,blobs,rows

def payload_header(rows):
 if tuple(r['identity'] for r in rows)!=IDS:raise ValueError('Invalid turret rows')
 lines=[f' {{{r["identity"]}u,{r["bytes"]}u,8u,24u,28u,6,7,"newshf-turret/{name(r["identity"])}",UINT64_C(0x{r["payload_fnv"]})}},' for r in rows]
 return ('/* Generated by build_current_turret_newshf.py. */\n#ifndef CURRENT_TURRET_NEWSHF_HD_ASSETS_H\n#define CURRENT_TURRET_NEWSHF_HD_ASSETS_H\n#include "global_asset_registry.h"\nenum { TURRET_NEWSHF_HD_RESOURCE_COUNT = 2 };\nstatic const GlobalAssetResource turret_newshf_hd_resources[2] = {\n'+'\n'.join(lines)+'\n};\n#endif\n').encode()
def load(root):
 raw=read(root,SELECTION);selected,pngs,blobs,rows=generate(root,raw)
 expected=dict(schema='opentyrian-turret-newshf-compatibility-v1',selection=SELECTION,files=rows)
 if parse(read(root,MAPPING))!=expected:raise ValueError('Turret mapping differs from derived rows')
 for p,data in pngs.items():
  if read(root,p)!=data:raise ValueError('Changed turret derived PNG')
 for identity,data in blobs.items():
  if read(root,ROOT+'/'+name(identity))!=data:raise ValueError('Changed turret transport')
 if read(root,HEADER)!=payload_header(rows):raise ValueError('Changed turret header')
 return {row['destination']:row for row in rows}
