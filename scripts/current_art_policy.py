"""Bounded semantic authoring identities; these are not byte-dedup groups.

Artwork versions may change payloads, never the original source/role identity.
Adding a family to this policy is a separate reviewed code change.
"""
PROFILES = {
    'pulse': {'ids': (80058, 80059, 80060, 80062, 80165)},
    'vulcan': {'ids': (80067, 80070)},
    'cash25': {'ids': (1120007, 1120008, 1120009, 1120010, 1120011, 1120012, 1130185)},
    'cash50': {'ids': (1160026, 1160027, 1160028, 1160029, 1160030, 1160031, 1170204)},
    'cash75': {'ids': (1140020, 1140021, 1140022, 1140023, 1140024, 1140025, 1150223)},
    'gem100': {'ids': (1180032, 1180033, 1180034, 1180035, 1180036, 1190169)},
    'gem250': {'ids': (1200014, 1200015, 1200016, 1200017, 1200018, 1210188)},
}
ALL_IDS = tuple(i for p in PROFILES.values() for i in p['ids'])
REGISTRY = 'assets/hd/global-assets-v1/registry.json'
LEGACY_HEADER = 'src/current_art_payload_pins.h'

def profile(family):
    if family not in PROFILES:
        raise ValueError('Unsupported authoring family')
    return dict(PROFILES[family], family=family,
                selection=f'assets/hd/authoring/{family}-current.json',
                mapping=f'packaging/current-{family}-compatibility.json',
                compatibility=f'assets/hd/current-compat/{family}')

def compatibility_name(identity):
    """Pinned consumer name, not a filename inferred from pixel equality."""
    for family, policy in PROFILES.items():
        if identity not in policy['ids']:
            continue
        if family in ('pulse', 'vulcan'):
            return f'bullet-{identity-80000}-8.hda'
        stem = family.replace('cash', 'coin')
        slot = identity % 10000
        role = 'value-newsh6' if identity == policy['ids'][-1] else 'bank11'
        return f'{stem}-{role}-{slot}-8.hda'
    raise ValueError('Unsupported art identity')

def payload_macro(family, identity):
    if family == 'vulcan':
        return f'CURRENT_VULCAN_{identity-80000}_RGBA'
    return f'CURRENT_{family.upper()}_{identity}_RGBA'

def geometry(identity):
    if identity not in ALL_IDS:
        raise ValueError('Unsupported art identity')
    return [identity, 8, 12, 14, 2**32-1 if identity == 80059 else 0, 0]

def legacy_header(resources):
    by_id = {r['identity']: r for r in resources}
    lines = ['/* Generated by the current-art authoring workflow. Payloads only.',
             ' * Original source-bank, slot and role pins remain in render_mirror.c. */',
             '#ifndef CURRENT_ART_PAYLOAD_PINS_H', '#define CURRENT_ART_PAYLOAD_PINS_H']
    for family, policy in PROFILES.items():
        if family == 'pulse':
            continue
        for identity in policy['ids']:
            lines.append(f'#define {payload_macro(family, identity)} UINT64_C(0x{by_id[identity]["payload_fnv64"]})')
    lines.extend(['#endif', ''])
    return '\n'.join(lines).encode()

