"""One editable single missile master duplicated exactly for NEWSHF records2/500.

Fixed bank10 quartet169/170/188/189, palette5, geometry24x28 and anchor6/7.
Smooth alpha is preserved inside the immutable original support only. No smoke,
movement, attack or animation is generated by this purely bitmap recipe.
"""
import io
import struct
from PIL import Image
from current_guided_compatibility import read, parse, sha, image
from build_newshf_hd import fnv
INPUT_ROOT='authoring-inputs/newshf-dualmissile'
ROOT='assets/hd/current-compat/newshf-dualmissile'
HEADER='src/current_dualmissile_newshf_hd_assets.h'
SELECTION='assets/hd/authoring/newshf-dualmissile.json'
MAPPING='packaging/current-dualmissile-newshf-compatibility.json'
IDS=(2100015,)
SCHEMA='opentyrian-dualmissile-newshf-authoring-v1'
REVISION='current-single-source-dualmissile-newshf-one'
INPUTS=('single-master.png','native-mask.png')
MASK_SHA256='bfe38fafcaa1944ba42cb3b7b3be364ac937bbcdd2a14035b4b6805d7a38a1d6'
RECORDS=(2,500)
def name(i):
 if type(i) is not int or i not in IDS:raise ValueError('Unknown dualmissile identity')
 return f'newshf-role{i}-8.hda'
def png(i):return INPUT_ROOT+'/derived/'+name(i).replace('.hda','.png')
def generated_paths():return {png(i) for i in IDS}
def input_paths(root):return {INPUT_ROOT+'/'+n for n in INPUTS}|{SELECTION}
def encode_png(im):
 out=io.BytesIO();im.save(out,format='PNG',optimize=False);return out.getvalue()
def generate(root,raw,candidate=False):
 selected=parse(raw)
 if not isinstance(selected,dict) or set(selected)!={'schema','version','inputs'} or selected['schema']!=SCHEMA:raise ValueError('Invalid dualmissile selection')
 if not isinstance(selected['version'],str) or not 1<=len(selected['version'])<=128:raise ValueError('Invalid dualmissile version')
 expected={INPUT_ROOT+'/'+n for n in INPUTS}
 if not isinstance(selected['inputs'],dict) or set(selected['inputs'])!=expected:raise ValueError('Invalid fixed dualmissile input closure')
 for p,h in selected['inputs'].items():
  if sha(read(root,p))!=h:raise ValueError('Changed dualmissile input: '+p)
 raw_mask=read(root,INPUT_ROOT+'/native-mask.png')
 if sha(raw_mask)!=MASK_SHA256:raise ValueError('Immutable dualmissile native mask changed')
 mask=Image.open(io.BytesIO(raw_mask)).convert('L')
 if mask.size!=(12,28) or not set(mask.tobytes())<={0,255}:raise ValueError('Invalid dualmissile native mask')
 single=image(read(root,INPUT_ROOT+'/single-master.png'),(96,224))
 enlarged=mask.resize(single.size,Image.Resampling.NEAREST)
 if any(a and not m for a,m in zip(single.getchannel('A').tobytes(),enlarged.tobytes())):raise ValueError('Dualmissile art leaves original native support')
 if not any(single.getchannel('A').tobytes()):raise ValueError('Empty dualmissile master')
 # Alpha-composite onto transparent canonical canvas also clears RGB behind A0.
 piece=Image.new('RGBA',(192,224));piece.alpha_composite(single);piece.alpha_composite(single,(96,0))
 if piece.crop((0,0,96,224)).tobytes()!=piece.crop((96,0,192,224)).tobytes():raise ValueError('Missiles must share one exact master')
 identity=IDS[0];data=encode_png(piece)
 blob=struct.pack('<4s6I',b'HDR1',identity,8,24,28,6,7)+piece.tobytes()
 rows=[dict(identity=identity,records=list(RECORDS),base=169,source_path=ROOT+'/'+name(identity),destination='assets/global/newshf-dualmissile/'+name(identity),source_png=png(identity),source_png_sha256=sha(data),bytes=len(blob),sha256=sha(blob),payload_fnv=f'{fnv(blob[28:]):016x}')]
 return selected,{png(identity):data},{identity:blob},rows
def payload_header(rows):
 if tuple(r['identity'] for r in rows)!=IDS:raise ValueError('Invalid dualmissile rows')
 lines=[f' {{{r["identity"]}u,{r["bytes"]}u,8u,24u,28u,6,7,"newshf-dualmissile/{name(r["identity"])}",UINT64_C(0x{r["payload_fnv"]})}},' for r in rows]
 return ('/* Generated by build_current_dualmissile_newshf.py. */\n#ifndef CURRENT_DUALMISSILE_NEWSHF_HD_ASSETS_H\n#define CURRENT_DUALMISSILE_NEWSHF_HD_ASSETS_H\n#include "global_asset_registry.h"\nenum { DUALMISSILE_NEWSHF_HD_RESOURCE_COUNT = 1 };\nstatic const GlobalAssetResource dualmissile_newshf_hd_resources[1] = {\n'+'\n'.join(lines)+'\n};\n#endif\n').encode()
def load(root):
 raw=read(root,SELECTION);selected,pngs,blobs,rows=generate(root,raw)
 expected=dict(schema='opentyrian-dualmissile-newshf-compatibility-v1',selection=SELECTION,files=rows)
 if parse(read(root,MAPPING))!=expected:raise ValueError('Dualmissile mapping differs from derived rows')
 for p,data in pngs.items():
  if read(root,p)!=data:raise ValueError('Changed dualmissile derived PNG')
 for identity,data in blobs.items():
  if read(root,ROOT+'/'+name(identity))!=data:raise ValueError('Changed dualmissile transport')
 if read(root,HEADER)!=payload_header(rows):raise ValueError('Changed dualmissile header')
 return {row['destination']:row for row in rows}
